"""
Writes e2e/flows/20-offline-modules.yaml: opens every module of the app by its address with the phone offline and checks
that none of them shows "Can't reach the KH POS server" (or a crash screen).

Run from the repo root:  python e2e/make_offline_flow.py
"""
import re

routes = re.findall(r"route: '([^']*)'", open('src/lib/modules.ts', encoding='utf-8').read())
# modules that open from a list rather than by their own address are not in the list; the settings screens are:
routes += ['/settings-general', '/accessibility', '/users', '/deliveries', '/payment-methods']

lines = [
    '# Generated by e2e/make_offline_flow.py: do not edit by hand.',
    '# Every module is opened with the phone OFFLINE. The phone must have been online for a few minutes before,',
    '# with "All modules saved" in the sync sheet (flow 10). Needs: APP_ID, LINK_BASE (see e2e/README.md).',
    'appId: ${APP_ID}',
    '---',
    '- launchApp:',
    '    stopApp: false',
    '- setAirplaneMode: enabled',
    '- extendedWaitUntil:',
    '    visible: "Offline"',
    '    timeout: 40000',
]
for r in routes:
    name = r.strip('/').replace('/', '-') or 'home'
    lines += [
        f'# --- {r}',
        '- openLink: "${LINK_BASE}' + r.lstrip('/') + '"',
        '- waitForAnimationToEnd:',
        '    timeout: 4000',
        '- assertNotVisible: "Can\'t reach the KH POS server.*"',
        '- assertNotVisible: "Something went wrong.*"',
        f'- takeScreenshot: "offline-{name}"',
    ]
lines += ['- setAirplaneMode: disabled', '']
open('e2e/flows/20-offline-modules.yaml', 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print(len(routes), 'modules')
