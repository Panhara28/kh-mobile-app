#!/usr/bin/env node
// Copies the kh-pos-v2 API's business code into core/ so the phone runs the same features and rules as the web, on its
// own SQLite database (no server). Run again after changing kh-pos-v2:  node scripts/sync-core.mjs [path-to-kh-pos-v2]
//
// Only code is copied, never data. The server shell (NestJS controllers, Express, Prisma runtime) stays behind:
//   - core/routes.ts is generated from the NestJS controllers (same paths, same order, so the same route wins)
//   - local-overrides/ replaces the few files that talk to Prisma / Express (database, request, response)
//   - Node-only modules (fs, puppeteer, nodemailer...) resolve to src/local/shims/unavailable.js (metro.config.js)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const mobile = path.resolve(here, '..');
const v2 = path.resolve(process.argv[2] ?? path.join(mobile, '..', 'kh-pos-v2'));
const apiSrc = path.join(v2, 'apps', 'api', 'src');
const out = path.join(mobile, 'core');
const overrides = path.join(mobile, 'local-overrides');

if (!fs.existsSync(apiSrc)) {
  console.error(`kh-pos-v2 API not found at ${apiSrc}`);
  process.exit(1);
}

const DIRS = ['api', 'classes', 'lib', 'db', 'common', 'repository', 'dataloader', 'types', 'config', 'next-compat', 'generated/tables'];
const FILES = ['tz.ts', 'generated/tables.ts'];
const SKIP = new Set(['next-compat/host.ts']); // Express only

/** Relative `.js` specifiers -> extensionless (Metro and Jest resolve the .ts file); no JSON import attributes. */
function patchSource(rel, src) {
  let s = src
    .replace(/((?:from|import)\s*\(?\s*)(["'])(\.{1,2}\/[^"']+?)\.js\2/g, '$1$2$3$2')
    .replace(/(require\(\s*)(["'])(\.{1,2}\/[^"']+?)\.js\2/g, '$1$2$3$2')
    .replace(/\s+with\s*\{\s*type:\s*["']json["']\s*\}/g, '');
  if (rel === 'db/coerce.ts') {
    s = s
      .replace(/import \{ Prisma \} from "\.\.\/generated\/prisma\/client";\n/, '// SQL NULL for a JSON column (Prisma.DbNull on the server)\nconst Prisma = { DbNull: null };\n')
      .replace('\nfunction readValue(', '\nexport function readValue(');
    if (!s.includes('export function readValue(') || s.includes('generated/prisma')) throw new Error('db/coerce.ts changed: update the patch in sync-core.mjs');
  }
  return '// @ts-nocheck\n// GENERATED from kh-pos-v2 by scripts/sync-core.mjs. Do not edit: change kh-pos-v2, then sync.\n' + s;
}

fs.rmSync(out, { recursive: true, force: true });
let count = 0;
const copy = (from, rel) => {
  if (SKIP.has(rel)) return;
  const st = fs.statSync(from);
  if (st.isDirectory()) {
    for (const name of fs.readdirSync(from)) copy(path.join(from, name), rel ? `${rel}/${name}` : name);
    return;
  }
  if (!/\.(ts|json)$/.test(from) || /\.(test|spec)\.ts$/.test(from)) return;
  const to = path.join(out, rel);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  if (rel.endsWith('.ts')) fs.writeFileSync(to, patchSource(rel, fs.readFileSync(from, 'utf8')));
  else fs.copyFileSync(from, to);
  count++;
};
for (const d of DIRS) if (fs.existsSync(path.join(apiSrc, d))) copy(path.join(apiSrc, d), d);
for (const f of FILES) if (fs.existsSync(path.join(apiSrc, f))) copy(path.join(apiSrc, f), f);

// phone versions of the server-shell files
let overridden = 0;
const overlay = (dir, rel = '') => {
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    const r = rel ? `${rel}/${name}` : name;
    if (fs.statSync(p).isDirectory()) overlay(p, r);
    else {
      fs.mkdirSync(path.dirname(path.join(out, r)), { recursive: true });
      fs.copyFileSync(p, path.join(out, r));
      overridden++;
    }
  }
};
overlay(overrides);

// routes, from the generated NestJS controllers: modules in index.ts order, routes in declaration order
const modDir = path.join(apiSrc, 'modules');
const order = [...fs.readFileSync(path.join(modDir, 'index.ts'), 'utf8').matchAll(/from "\.\/([^"]+)\.js"/g)].map((m) => m[1]);
const routes = [];
for (const mod of order) {
  const src = fs.readFileSync(path.join(modDir, `${mod}.ts`), 'utf8');
  const imports = Object.fromEntries([...src.matchAll(/import \* as (r\d+) from "\.\.\/(api\/[^"]+)\.js";/g)].map((m) => [m[1], m[2]]));
  for (const m of src.matchAll(/@(Get|Post|Put|Patch|Delete)\("([^"]*)"\)[\s\S]*?runRoute\((r\d+)\.(\w+)/g)) {
    const file = imports[m[3]];
    if (!file) throw new Error(`${mod}: no import for ${m[3]}`);
    routes.push({ method: m[1].toUpperCase(), path: `/api/${m[2]}`, file, exp: m[4] });
  }
}
const files = [...new Set(routes.map((r) => r.file))];
fs.writeFileSync(
  path.join(out, 'routes.ts'),
  `// GENERATED by scripts/sync-core.mjs from kh-pos-v2 apps/api/src/modules. Do not edit.\n` +
    `/* eslint-disable */\n// Each route file is loaded the first time it is called (fast app start).\n` +
    `const load: Record<string, () => any> = {\n${files.map((f) => `  ${JSON.stringify(f)}: () => require(${JSON.stringify('./' + f)}),`).join('\n')}\n};\n\n` +
    `export const ROUTES: { method: string; path: string; file: string; exp: string }[] = ${JSON.stringify(routes, null, 0).replace(/\},\{/g, '},\n  {')};\n\n` +
    `export function loadRoute(file: string): any {\n  return load[file]!();\n}\n`,
);

// the database schema, as SQL in order (the phone runs it on first start)
const migDir = path.join(v2, 'apps', 'api', 'prisma', 'migrations');
const migrations = fs
  .readdirSync(migDir)
  .filter((d) => fs.existsSync(path.join(migDir, d, 'migration.sql')))
  .sort()
  .map((d) => ({ name: d, sql: fs.readFileSync(path.join(migDir, d, 'migration.sql'), 'utf8') }));
fs.writeFileSync(path.join(out, 'migrations.json'), JSON.stringify(migrations));

fs.writeFileSync(
  path.join(out, 'README.md'),
  '# core (generated)\n\nThe kh-pos-v2 API code, copied by `node scripts/sync-core.mjs`, running on the phone against its own SQLite\n' +
    'database (see `src/local`). Do not edit here: change kh-pos-v2 (or `local-overrides/` for the phone shell), then sync.\n',
);
console.log(`core/: ${count} files (${overridden} phone overrides), ${routes.length} routes, ${migrations.length} migrations from ${v2}`);
